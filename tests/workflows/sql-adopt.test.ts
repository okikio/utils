/** A schema made elsewhere is read from the catalog, defined by generated code, checked for drift and queried. */
import { after, before, describe, it } from 'node:test';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { expect } from '@std/expect';
import postgres from 'postgres';
import { temporal } from '@okikio/duration/temporal';
import * as sql from '@okikio/sql/postgres';
import { types } from '@okikio/sql/postgres';
import { drift, generate, inspect } from '@okikio/sql/postgres/adopt';
import { database } from '@okikio/sql/postgres/postgresjs';

const url = process.env.UTILS_WORKFLOW_TEST_DATABASE_URL;
if (!url) throw new Error('Adoption checks require a disposable PostgreSQL database.');
const client = postgres(url, { max: 2, onnotice() {} });
const db = database(client);
const folder = mkdtempSync(join(tmpdir(), 'sql-adopt-'));

before(async () => {
	await client.unsafe(`
		drop schema if exists "Foreign App" cascade;
		create schema "Foreign App";
		create type "Foreign App".mood as enum ('sad', 'ok', 'happy');
		create type "Foreign App".point as (x double precision, label text);
		create domain "Foreign App".email as text check (value ~ '@');
		create table "Foreign App"."User" (
			"id" integer generated by default as identity primary key,
			"email" "Foreign App".email not null,
			"handle" varchar(40) not null,
			"full name" text,
			"mood" "Foreign App".mood not null default 'ok',
			"balance" numeric(12, 2) not null default 0,
			"cents" bigint not null default 0,
			"dollars" numeric generated always as (cents / 100.0) stored,
			"tags" text[],
			"spot" "Foreign App".point,
			"createdAt" timestamp(3) not null,
			"updatedAt" timestamp(3) not null,
			"seen_at" timestamptz
		);
		create view "Foreign App".rich as select "id", "handle" from "Foreign App"."User" where cents > 100;
	`);
});
after(async () => {
	await client.unsafe('drop schema if exists "Foreign App" cascade');
	await client.end({ timeout: 2 });
	rmSync(folder, { recursive: true, force: true });
});

describe('adopting a schema made elsewhere', () => {
	it('reads tables, views, composite types, enums and keys from the catalog', async () => {
		const info = await inspect(db, ['Foreign App']);
		expect(info.tables.map((table) => `${table.name}:${table.kind}:${table.primaryKey.join('+')}`)).toEqual([
			'User:table:id',
			'point:composite:',
			'rich:view:',
		]);
		expect(info.enums).toEqual({ 'Foreign App.mood': ['sad', 'ok', 'happy'] });
		const user = info.tables[0]!.columns;
		expect(user.find((column) => column.name === 'id')).toMatchObject({ identity: 'by default', nullable: false });
		expect(user.find((column) => column.name === 'dollars')).toMatchObject({ generated: true });
		expect(user.find((column) => column.name === 'email')).toMatchObject({ typeKind: 'd', base: 'text' });
		expect(user.find((column) => column.name === 'tags')?.element).toEqual({
			schema: 'pg_catalog',
			name: 'text',
			kind: 'b',
		});
	});

	it('generates definitions that pass the drift check and run queries', async () => {
		const from = pathToFileURL(join(import.meta.dirname, '../../packages/sql/postgres/mod.ts')).href;
		const file = join(folder, 'tables.ts');
		writeFileSync(file, generate(await inspect(db, ['Foreign App']), { from }));
		const generated = await import(pathToFileURL(file).href) as Record<string, sql.Table<sql.Columns>>;
		const User = generated.User!;
		expect(Object.keys(generated).sort()).toEqual(['Foreign_AppSchema', 'User', 'rich']);
		const problems = await drift(db, [User, generated.rich!]);
		expect(problems.filter((item) => item.severity === 'error')).toEqual([]);
		expect(problems.map((item) => `${item.table} ${item.column}`)).toEqual([
			'Foreign App.User handle',
			'Foreign App.rich handle',
		]);
		const at = temporal.Instant.from('2026-01-02T03:04:05.123Z');
		const row = {
			email: 'a@x',
			handle: 'a',
			'full name': 'Ada L',
			cents: 25_000n,
			tags: ['x', null],
			spot: { x: 1.5, label: null },
			createdAt: at,
			updatedAt: at,
		};
		const c = User.c as Record<string, sql.Column<unknown>>;
		const [back] = await sql.rows(
			db,
			sql.insert(User, row as never).returning({
				mood: c.mood!,
				dollars: c.dollars!,
				tags: c.tags!,
				name: c['full name']!,
			}),
		);
		expect(back).toEqual({ mood: 'ok', dollars: '250.0000000000000000', tags: ['x', null], name: 'Ada L' });
		expect(() => sql.createTable(User)).toThrow('owned elsewhere');
		expect(() => sql.toQuery(sql.update(User, { dollars: '1' } as never))).toThrow('written by the database');
	});

	it('reports definitions that would fail or change values', async () => {
		const space = sql.schema('Foreign App', { owned: false });
		const wrong = space.table('User', {
			id: sql.column(types.integer),
			email: sql.column(types.text()),
			cents: sql.column(types.integer),
			createdAt: sql.column(types.timestamptz),
			'full name': sql.column(types.text()),
			balance: sql.column(types.numeric).default('0'),
			dollars: sql.column(types.numeric).nullable(),
			missing: sql.column(types.text()).nullable(),
			updatedAt: sql.column(types.timestamp).default(sql.fn.now()),
		});
		const problems = await drift(db, [wrong, space.table('gone', {})]);
		expect(problems.filter((item) => item.severity === 'error').map((item) => `${item.table} ${item.column ?? ''}`))
			.toEqual([
				'Foreign App.User cents',
				'Foreign App.User createdAt',
				'Foreign App.User full name',
				'Foreign App.User dollars',
				'Foreign App.User missing',
				'Foreign App.User updatedAt',
				'Foreign App.User handle',
				'Foreign App.gone ',
			]);
	});

	it('maps keys to column names and writes the values the application owns', async () => {
		const space = sql.schema('Foreign App', { owned: false });
		const users = space.table('User', {
			id: sql.column(types.integer).filled(),
			email: sql.column(types.text()),
			handle: sql.column(types.text()),
			seenAt: sql.column(types.timestamptz).nullable().named('seen_at'),
			createdAt: sql.column(types.timestamp).onInsert(() => sql.fn.now()),
			updatedAt: sql.column(types.timestamp).onInsert(() => sql.fn.now()).onUpdate(() => sql.fn.now()),
		});
		const u = users.c;
		const seen = temporal.Instant.from('2026-05-01T00:00:00Z');
		const [made] = await sql.rows(
			db,
			sql.insert(users, { email: 'b@x', handle: 'b', seenAt: seen }).returning({ id: u.id, seenAt: u.seenAt }),
		);
		expect(made!.seenAt).toEqual(seen);
		const before = await sql.one(db, sql.select({ updatedAt: u.updatedAt }).from(users).where(u.id.eq(made!.id)));
		await new Promise((resolve) => setTimeout(resolve, 5));
		await sql.execute(db, sql.update(users, { handle: 'b2' }).where(u.id.eq(made!.id)));
		const after = await sql.one(
			db,
			sql.select({ updatedAt: u.updatedAt, handle: u.handle }).from(users).where(u.id.eq(made!.id)),
		);
		expect(after!.handle).toBe('b2');
		expect(temporal.Instant.compare(after!.updatedAt, before!.updatedAt)).toBe(1);
		expect(sql.toQuery(sql.select({ seenAt: u.seenAt }).from(users)).text).toContain('"Foreign App"."User"."seen_at"');
	});
});
